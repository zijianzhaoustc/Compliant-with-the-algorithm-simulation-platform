function tbl = buildInferenceSummaryTable(r)
%BUILDINFERENCESUMMARYTABLE One row; units and identifiable targets explicit.
mu=NaN; s1=NaN; s2=NaN; alpha=NaN; delta=NaN; b=NaN;
if ~isempty(r.folds)
    weights=cellfun(@(x)x.evaluation.Teff,r.folds); weights=weights/sum(weights);
    mu=sum(cellfun(@(x)x.fit.model.mu,r.folds).*weights);
    s1=sum(cellfun(@(x)x.fit.model.sigma1,r.folds).*weights);
    s2=sum(cellfun(@(x)x.fit.model.sigma2,r.folds).*weights);
    alpha=sum(cellfun(@(x)x.fit.model.alpha,r.folds).*weights);
    delta=sum(cellfun(@(x)x.fit.model.delta,r.folds).*weights);
    b=sum(cellfun(@(x)x.evaluation.b,r.folds));
end
ci=r.bootstrap.CI95;
tbl=table(r.Npair_core,r.Tcore,r.Cpair,r.Npair_fulltime,r.T,r.Fdomain,r.Fwindow, ...
    mu*1e9,s1*1e9,s2*1e9,alpha,delta*1e9,b,r.etaB_given_A,r.etaB_apparent, ...
    ci(1,1),ci(2,1),r.bootstrap.standardUncertainty(1),r.status,r.validation_score,r.truth_Nrec, ...
    string(r.exposureSource),strjoin(r.warnings,';'),r.bootstrap.status,r.bootstrap.failureCount, ...
    r.bootstrap.requestedCount,r.totalCandidatePairs,r.maxResidentPairs,r.spilledToDisk, ...
    'VariableNames',{'inference_Npair_core','inference_Tcore_s','inference_Cpair_cps', ...
    'inference_Npair_fulltime','acquisition_T_s','inference_Fdomain','inference_Fwindow', ...
    'inference_tau0_ns','inference_sigma1_ns','inference_sigma2_ns','inference_alpha', ...
    'inference_delta_ns','inference_b_count_per_s','inference_etaB_given_A','inference_etaB_apparent', ...
    'inference_Cpair_CI95_low_cps','inference_Cpair_CI95_high_cps','inference_Cpair_u_cps', ...
    'inference_status','inference_validation_score','inference_truth_Nrec','exposure_source', ...
    'inference_warnings','bootstrap_status','bootstrap_failed','bootstrap_requested', ...
    'candidate_pairs','max_resident_pairs','spilled_to_disk'});
for k=4:5
    suffix="apparent"; if k==5, suffix="given_A"; end
    tbl.("inference_etaB_"+suffix+"_CI95_low")=ci(1,k);
    tbl.("inference_etaB_"+suffix+"_CI95_high")=ci(2,k);
end
end
