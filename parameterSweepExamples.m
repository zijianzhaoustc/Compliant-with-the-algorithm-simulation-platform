function c = parameterSweepExamples(mode)
%PARAMETERSWEEPEXAMPLES Reproducible small 32-row and research configurations.
if nargin<1, mode="smoke"; end
c=scanDefaultConfig(); c.baseParams.measurementTime=.01;
c.baseParams.optics.A.delay=0; c.baseParams.optics.B.delay=0;
c.baseParams.algorithm.accidentalMethod="side-window"; c.seeds=[1 2];
c.factors=[scanFactor("source.pairRate",[1e4 3e4]); ...
    scanFactor("algorithm.binWidth",[10 20]); ...
    scanFactor("algorithm.windowMultiplier",[1 3]); ...
    scanFactor("algorithm.sideWindowPairs",[1 2])];
if string(mode)=="research"
    c.baseParams.measurementTime=.1; c.seeds=1:5;
    c.factors=[scanFactor("source.pairRate",[1e4 1e5]); ...
        scanFactor("algorithm.histHalfRange",[20 50]); ...
        scanFactor("algorithm.binWidth",[10 50 100]); ...
        scanFactor("algorithm.windowMultiplier",[0 1 3]); ...
        scanFactor("algorithm.sideWindowPairs",[1 2]); ...
        scanFactor("algorithm.accidentalMethod",["theory","side-window","time-shift"]); ...
        scanFactor("algorithm.timeShiftStart",[1 5]); ...
        scanFactor("algorithm.timeShiftStep",1); scanFactor("algorithm.timeShiftCount",3)];
elseif string(mode)~="smoke"
    error('CoincidenceSim:ScanExample','Use smoke or research.');
end
end
