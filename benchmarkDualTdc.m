function result=benchmarkDualTdc(n)
%BENCHMARKDUALTDC Full MHz-scale four-stream analysis; no truncated prefix.
if nargin<1, n=1e6; end
validateattributes(n,{'numeric'},{'scalar','integer','positive'});
saved=rng; cleanup=onCleanup(@()rng(saved)); rng(714);
physical1=cumsum(-log(rand(n,1))/1e6);
physical2=physical1+5e-9+100e-12*randn(n,1);
keepF1=rand(n,1)>.02; keepF2=rand(n,1)>.02;
keepS1=rand(n,1)>.01; keepS2=rand(n,1)>.01;
data=struct('F1',physical1(keepF1)+10e-12*randn(nnz(keepF1),1), ...
    'F2',physical2(keepF2)+10e-12*randn(nnz(keepF2),1), ...
    'S1',.1+1.000025*physical1(keepS1)+8e-12*randn(nnz(keepS1),1), ...
    'S2',.1+1.000025*physical2(keepS2)+8e-12*randn(nnz(keepS2),1));
for name=["F1","F2","S1","S2"], data.(name)=sort(data.(name)); end
o=defaultDualTdcOptions(); timer=tic; out=analyzeDualTdc(data,o); elapsed=toc(timer);
result=table(n,numel(data.F1)+numel(data.F2)+numel(data.S1)+numel(data.S2), ...
    elapsed,string(out.status),out.alignment.relativeClockPpm, ...
    out.F.metrics.rate1_cps,out.F.histogram.maxPairScratchCount,o.maxPairChunk, ...
    'VariableNames',{'electric_events_per_channel','recorded_timestamps_total', ...
    'elapsed_s','alignment_status','relative_clock_ppm','F1_rate_cps', ...
    'max_pair_scratch_count','pair_chunk_limit'});
if out.status~="ALIGNED", error('DualTDC:Benchmark','MHz benchmark failed alignment: %s',out.alignment.reason); end
clear cleanup
end
