function p=researchParams(p)
%RESEARCHPARAMS Add research-only options without changing legacy defaults.
d=struct('researchAnalysis',true,'fixedPeakCenter',0,'segmentDuration',.1, ...
    'timeShiftMode',"overlap",'pairRecovery',"joint-side",'peakModel',"gaussian", ...
    'uncertaintyMethod',"delta",'bootstrapBlockDuration',.05,'bootstrapReplicates',100, ...
    'bootstrapSeed',9237,'pairChunkSize',65536,'storageMode',"stream", ...
    'minCapture',.02,'minRecoveryDenominator',.01,'residualThreshold',2, ...
    'sideTailThreshold',.05,'sideAsymmetryThreshold',3.5,'stationarityAlpha',.001, ...
    'backgroundConflictThreshold',3.5,'qualityCalibrated',false,'correlatedBackgroundPossible',false);
p.algorithm=mergeParamsWithDefaults(d,p.algorithm);
if ~isfield(p,'scenarios'), p.scenarios=researchScenarioDefaults();
else, p.scenarios=mergeParamsWithDefaults(researchScenarioDefaults(),p.scenarios); end
if p.scenarios.correlatedBackgroundRate>0
    % Known configured ambiguity, not a classifier based on hidden labels.
    p.algorithm.correlatedBackgroundPossible=true;
end
end
